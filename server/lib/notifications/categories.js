/**
 * Which tab a notice belongs on.
 *
 * One table from kind to category, read when the row is written and stored
 * beside it. Kept in code rather than derived in SQL so the migration that
 * backfilled existing rows and the drain that writes new ones agree, and so
 * a new kind has to be placed somewhere before it can be sent.
 */
export const NOTIFICATION_CATEGORIES = Object.freeze(['BOOKING', 'DISPATCH', 'FINANCE', 'APPROVAL', 'DEADLINE', 'SYSTEM']);

const DISPATCH = 'DISPATCH';
const BOOKING = 'BOOKING';
const FINANCE = 'FINANCE';
const APPROVAL = 'APPROVAL';
const DEADLINE = 'DEADLINE';
const SYSTEM = 'SYSTEM';

export const CATEGORY_OF = Object.freeze({
    TRANSFER_ASSIGNMENT_OFFERED: DISPATCH,
    TRANSFER_ASSIGNMENT_ACCEPTED: DISPATCH,
    TRANSFER_ASSIGNMENT_DECLINED: DISPATCH,
    TRANSFER_ASSIGNMENT_REVOKED: DISPATCH,
    TRANSFER_LEG_UNASSIGNED_ALERT: DISPATCH,
    TRANSFER_LEG_STATUS_CHANGED: DISPATCH,
    TRANSFER_LEG_NO_SHOW_REPORTED: DISPATCH,
    TRANSFER_BOOKING_CANCELLED: DISPATCH,
    TRANSFER_PICKUP_REMINDER: DISPATCH,
    TRANSFER_DRIVER_DETAILS: DISPATCH,
    TRANSFER_RATING_RECEIVED: DISPATCH,

    TOUR_REQUEST_OVERDUE: BOOKING,
    ORDER_REQUEST_OVERDUE: BOOKING,
    PACKAGE_KOSHER_ELIGIBILITY_CHANGED: SYSTEM,
    BOOKING_NEW: BOOKING,
    BOOKING_MODIFIED: BOOKING,

    BOOKING_AWAITING_APPROVAL: APPROVAL,
    BOOKING_APPROVED: APPROVAL,
    BOOKING_REJECTED: APPROVAL,
    BOOKING_APPROVAL_OVERDUE: APPROVAL,
    APPROVAL_REQUESTED: APPROVAL,
    APPROVAL_DECIDED: APPROVAL,

    DEADLINE_PAYMENT_UPCOMING: DEADLINE,
    DEADLINE_CANCELLATION_UPCOMING: DEADLINE,
    DEADLINE_CONFIRMATION_UPCOMING: DEADLINE,

    MAIL_PROVIDER_ALERT: SYSTEM,
    FINANCE_PAYABLE_DUE: DEADLINE,
    FINANCE_PAYABLE_OVERDUE: DEADLINE,
    FINANCE_RECEIVABLE_OVERDUE: DEADLINE,
    FINANCE_PAYMENT_RECEIVED: FINANCE,
    FINANCE_INVOICE_ISSUED: FINANCE,
    FINANCE_INVOICE_SYNC_FAILED: FINANCE,
    FINANCE_CREDIT_WARNING: FINANCE,

    SYSTEM
});

/** A kind nobody placed is a bug; it lands on the system tab rather than nowhere. */
export const categoryOf = (kind) => CATEGORY_OF[kind] ?? SYSTEM;
