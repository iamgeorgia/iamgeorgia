// Transfer UI journey only (submit scoped to the booking form, not the footer newsletter form).
import { launch, newPage, shot, record, CLIENT, API, api, summarizeErrors, sql } from './lib.mjs';
const browser = await launch();
const ts = Date.now();
const errs = (page) => { const e = summarizeErrors(page, { ignore: [/speed-insights/, /\/api\/auth\/me$/, /_next\/image/, /r2\.dev/] }); return `${e.pageerrors.length} js, ${e.http.length} http>=400`; };
const clickCentered = async (loc) => { await loc.evaluate((el) => el.scrollIntoView({ block: 'center' })).catch(() => {}); await loc.click({ timeout: 15000 }); };
const { context, page } = await newPage(browser);
await page.goto(`${CLIENT}/transfers/search?from=tbilisi-airport&to=gudauri&date=2026-11-20&time=10:00&adults=2&children=0&luggage=2&cabinBags=0`, { waitUntil: 'networkidle' });
const offers = page.locator('main a[href^="/transfers/"][href*="from="]:not([href*="/transfers/sedan-"]):not([href*="/transfers/vehicle-"])');
await offers.first().waitFor({ timeout: 20000 });
await offers.first().click();
await page.waitForURL(/\/transfers\/(?!search)[^?]+\?from=/, { timeout: 30000 });
await page.waitForLoadState('networkidle');
const detailText = await page.locator('main').innerText();
const priceOnDetail = (detailText.match(/GEL\s?[\d,.]+/g) || [])[0];
await clickCentered(page.locator('main a[href*="/transfers/booking"]').first());
await page.waitForURL(/\/transfers\/booking/, { timeout: 30000 });
await page.waitForLoadState('networkidle');
const form = page.locator('form:has(#firstName)');
const submit = form.locator('button[type="submit"]').first();
record('UT2', 'Choosing an offer opens the booking form with the quote', (await page.locator('#firstName').count()) === 1 && (await submit.count()) === 1 ? 'PASS' : 'FAIL', page.url().replace(CLIENT, '').slice(0, 60));
const summaryText = await page.locator('main').innerText();
record('UT2b', 'Booking form shows the same fare as the detail page', priceOnDetail && summaryText.includes(priceOnDetail) ? 'PASS' : 'INFO', `detail=${priceOnDetail} formHas=${priceOnDetail ? summaryText.includes(priceOnDetail) : 'n/a'}`);
await clickCentered(submit); await page.waitForTimeout(600);
const invalid = await page.locator('form:has(#firstName) [aria-invalid="true"]').count();
record('UT3', 'Empty transfer form is blocked with field errors (4 required fields)', invalid >= 3 && /\/transfers\/booking/.test(page.url()) ? 'PASS' : 'FAIL', `aria-invalid=${invalid}`);
const email = `qa.ui.transfer+${ts}@example.test`;
await page.fill('#firstName', 'Ui'); await page.fill('#lastName', 'Passenger'); await page.fill('#email', email); await page.fill('#phone', '12');
await clickCentered(submit); await page.waitForTimeout(500);
record('UT3b', 'Short phone number is refused client-side', (await page.locator('form:has(#firstName) [aria-invalid="true"]').count()) >= 1 && /\/transfers\/booking/.test(page.url()) ? 'PASS' : 'FAIL', '');
await page.fill('#phone', '+995555000444'); await page.fill('#flightNumber', 'TK378');
const special = page.locator('#specialRequests'); if (await special.count()) await special.fill('UI transfer <script>alert(1)</script>');
const respP = page.waitForResponse((r) => r.url().endsWith('/api/transfers/bookings') && r.request().method() === 'POST', { timeout: 20000 }).catch(() => null);
await clickCentered(submit).catch(() => null);
await submit.click({ force: true, timeout: 1500 }).catch(() => null);
const resp = await respP;
await page.waitForURL(/\/transfers\/confirmation\//, { timeout: 20000 }).catch(() => {});
const ref = (page.url().match(/confirmation\/(TRF-\d+)/) || [])[1];
await shot(page, 'UT4-confirmation');
record('UT4', 'Transfer booking confirms and shows the confirmation page', resp?.status() === 201 && ref ? 'PASS' : 'FAIL', `api=${resp?.status()} ref=${ref} url=${page.url().replace(CLIENT, '').slice(0, 60)} ${errs(page)}`);
const dup = sql(`select count(*) from transfer_bookings where lead_passenger_email='${email}'`);
record('UT4b', 'Double-clicking the submit creates exactly one transfer booking', dup === '1' ? 'PASS' : 'FAIL', `rows=${dup}`);
if (ref) {
  const v = await api('GET', `/api/transfers/bookings/${ref}?email=${encodeURIComponent(email)}`);
  const shown = await page.locator('main').innerText();
  record('UT5', 'Confirmation shows reference, status and total consistent with the API', shown.includes(ref) && v.body.status === 'CONFIRMED' && shown.replace(/[,\s]/g, '').includes((v.body.totalCents / 100).toFixed(2)) ? 'PASS' : 'FAIL', `status=${v.body.status} total=${v.body.totalCents} flight=${v.body.flightNumber}`);
  record('UT5b', 'Special requests stored verbatim (escaped on render)', v.body.specialRequests === 'UI transfer <script>alert(1)</script>' && (await page.locator('main script').count()) === 0 ? 'PASS' : 'INFO', `stored="${v.body.specialRequests}"`);
  await page.reload({ waitUntil: 'networkidle' });
  record('UT5c', 'Transfer confirmation survives a reload', (await page.locator('main').innerText()).includes(ref) ? 'PASS' : 'FAIL', '');
  const cx = await api('POST', `/api/transfers/bookings/${ref}/cancel`, { body: { email, reason: 'QA cleanup' } });
  record('UT6', 'Cleanup: transfer cancelled via API', cx.status === 200 ? 'PASS' : 'INFO', `${cx.status}`);
}
await context.close();
await browser.close();
